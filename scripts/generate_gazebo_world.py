#!/usr/bin/env python3
"""Generate a Gazebo Harmonic world (SDF) from an AEGIS scenario file.

The scenario JSON is the single source of truth for environment geometry: the
dashboard draws it and Gazebo simulates it, so the two cannot drift apart.

    python scripts/generate_gazebo_world.py simulation/scenarios/open_field.json

The physics/scene/spherical-coordinates blocks mirror PX4 v1.17's
``Tools/simulation/gz/worlds/default.sdf`` so PX4's gz bridge behaves as it does
in the stock world. Gazebo's world frame is ENU, the same as the scenario frame.
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path
from xml.sax.saxutils import escape

REPO_ROOT = Path(__file__).resolve().parents[1]
WORLDS_DIR = REPO_ROOT / "simulation" / "gazebo" / "worlds"

# PX4 SITL default home (matches PX4's stock gz worlds).
HOME_LAT_DEG = 47.397971057728974
HOME_LON_DEG = 8.546163739800146
# Standard Gazebo models (people, vehicles) are fetched from Gazebo Fuel by name
# the first time a world is opened; Gazebo caches them under ~/.gz/fuel.
FUEL_MODELS = "https://fuel.gazebosim.org/1.0/OpenRobotics/models"


def _rgba(hex_color: str) -> str:
    h = hex_color.lstrip("#")
    r, g, b = (int(h[i : i + 2], 16) / 255.0 for i in (0, 2, 4))
    return f"{r:.3f} {g:.3f} {b:.3f} 1"


def _static_model(name: str, pose: str, geometry: str, color: str) -> str:
    rgba = _rgba(color)
    return f"""
    <model name="{escape(name)}">
      <static>true</static>
      <pose>{pose}</pose>
      <link name="link">
        <collision name="collision">
          <geometry>{geometry}</geometry>
        </collision>
        <visual name="visual">
          <geometry>{geometry}</geometry>
          <material>
            <ambient>{rgba}</ambient>
            <diffuse>{rgba}</diffuse>
          </material>
        </visual>
      </link>
    </model>"""


def build_world(scenario: dict) -> str:
    models: list[str] = []

    pad = scenario["landing_pad"]
    models.append(
        _static_model(
            "landing_pad",
            f"{pad['east_m']} {pad['north_m']} 0.01 0 0 0",
            f"<cylinder><radius>{pad['radius_m']}</radius><length>0.02</length></cylinder>",
            "#f2f2f2",
        )
    )

    for obstacle in scenario["obstacles"]:
        east, north = obstacle["east_m"], obstacle["north_m"]
        if obstacle["shape"] == "box":
            sx, sy, sz = obstacle["size_enu_m"]
            yaw = math.radians(obstacle.get("yaw_deg", 0.0))
            pose = f"{east} {north} {sz / 2} 0 0 {yaw:.6f}"
            geometry = f"<box><size>{sx} {sy} {sz}</size></box>"
        elif obstacle["shape"] == "cylinder":
            height = obstacle["height_m"]
            pose = f"{east} {north} {height / 2} 0 0 0"
            geometry = (
                f"<cylinder><radius>{obstacle['radius_m']}</radius>"
                f"<length>{height}</length></cylinder>"
            )
        else:
            raise ValueError(f"Unsupported obstacle shape: {obstacle['shape']}")
        models.append(_static_model(obstacle["id"], pose, geometry, obstacle["color"]))

    # Flat visual-only surfaces (roads, pavements): no collision, cannot be hit.
    for surface in scenario.get("surfaces", []):
        sx, sy = surface["size_enu_m"]
        yaw = math.radians(surface.get("yaw_deg", 0.0))
        rgba = _rgba(surface["color"])
        models.append(f"""
    <model name="{escape(surface["id"])}">
      <static>true</static>
      <pose>{surface["east_m"]} {surface["north_m"]} 0.005 0 0 {yaw:.6f}</pose>
      <link name="link">
        <visual name="visual">
          <geometry><box><size>{sx} {sy} 0.01</size></box></geometry>
          <material><ambient>{rgba}</ambient><diffuse>{rgba}</diffuse></material>
        </visual>
      </link>
    </model>""")

    # Staged detection targets. Always static: nothing here moves or is pursued.
    for prop in scenario.get("props", []):
        yaw = math.radians(prop.get("yaw_deg", 0.0))
        models.append(f"""
    <include>
      <name>{escape(prop["id"])}</name>
      <static>true</static>
      <pose>{prop["east_m"]} {prop["north_m"]} 0 0 0 {yaw:.6f}</pose>
      <uri>{FUEL_MODELS}/{escape(prop["model"])}</uri>
    </include>""")

    # Waypoint markers: visual only, so they can never be collided with.
    for i, wp in enumerate(scenario["demo_mission"]["waypoints"], start=1):
        models.append(f"""
    <model name="waypoint_marker_{i}">
      <static>true</static>
      <pose>{wp["east_m"]} {wp["north_m"]} 0.02 0 0 0</pose>
      <link name="link">
        <visual name="visual">
          <geometry><cylinder><radius>0.6</radius><length>0.02</length></cylinder></geometry>
          <material><ambient>1 0.55 0 1</ambient><diffuse>1 0.55 0 1</diffuse></material>
        </visual>
      </link>
    </model>""")

    size = scenario["ground"]["size_m"]
    name = scenario["gazebo_world"]
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by scripts/generate_gazebo_world.py from
     simulation/scenarios/{scenario["scenario_id"]}.json - do not edit by hand. -->
<sdf version="1.9">
  <world name="{name}">
    <physics type="ode">
      <max_step_size>0.004</max_step_size>
      <real_time_factor>1.0</real_time_factor>
      <real_time_update_rate>250</real_time_update_rate>
    </physics>
    <gravity>0 0 -9.8</gravity>
    <magnetic_field>6e-06 2.3e-05 -4.2e-05</magnetic_field>
    <atmosphere type="adiabatic"/>
    <scene>
      <grid>false</grid>
      <ambient>0.4 0.4 0.4 1</ambient>
      <background>0.62 0.74 0.86 1</background>
      <shadows>true</shadows>
    </scene>
    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>1 1</size></plane></geometry>
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>{size} {size}</size></plane></geometry>
          <material>
            <ambient>0.36 0.47 0.30 1</ambient>
            <diffuse>0.36 0.47 0.30 1</diffuse>
          </material>
        </visual>
      </link>
    </model>
    <light name="sunUTC" type="directional">
      <pose>0 0 500 0 0 0</pose>
      <cast_shadows>true</cast_shadows>
      <intensity>1</intensity>
      <direction>0.001 0.625 -0.78</direction>
      <diffuse>0.904 0.904 0.904 1</diffuse>
      <specular>0.271 0.271 0.271 1</specular>
    </light>{"".join(models)}
    <spherical_coordinates>
      <surface_model>EARTH_WGS84</surface_model>
      <world_frame_orientation>ENU</world_frame_orientation>
      <latitude_deg>{HOME_LAT_DEG}</latitude_deg>
      <longitude_deg>{HOME_LON_DEG}</longitude_deg>
      <elevation>0</elevation>
    </spherical_coordinates>
  </world>
</sdf>
"""


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    WORLDS_DIR.mkdir(parents=True, exist_ok=True)
    for path in sys.argv[1:]:
        scenario = json.loads(Path(path).read_text(encoding="utf-8"))
        out = WORLDS_DIR / f"{scenario['gazebo_world']}.sdf"
        out.write_text(build_world(scenario), encoding="utf-8")
        print(f"wrote {out.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
